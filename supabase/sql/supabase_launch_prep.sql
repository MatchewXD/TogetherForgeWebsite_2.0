-- ---------------------------------------------------------------------------
-- 2. Client error log
-- ---------------------------------------------------------------------------
create table if not exists public.client_error_log (
  id bigint generated by default as identity primary key,
  occurred_at timestamptz not null default now(),
  kind text not null default 'error',
  message text not null,
  stack text,
  path text,
  build text,
  user_agent text,
  session_key text,
  signed_in boolean not null default false
);

comment on table public.client_error_log is
  'Browser-side errors reported by the site. No user ids or IPs. Written only by log_client_error(); read only by staff through get_client_errors().';

create index if not exists idx_client_error_log_at
  on public.client_error_log (occurred_at desc);
create index if not exists idx_client_error_log_session_at
  on public.client_error_log (session_key, occurred_at desc);

alter table public.client_error_log enable row level security;
-- No policies on purpose: SECURITY DEFINER functions and service_role only.
revoke all on table public.client_error_log from public, anon, authenticated;
grant all on table public.client_error_log to service_role;

-- Anyone may report; the function bounds size and volume so the endpoint
-- cannot be used to fill the database.
create or replace function public.log_client_error(
  p_kind text,
  p_message text,
  p_stack text default null,
  p_path text default null,
  p_build text default null,
  p_user_agent text default null,
  p_session_key text default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  v_now timestamptz := clock_timestamp();
  v_message text := left(trim(coalesce(p_message, '')), 500);
  v_session text := left(trim(coalesce(p_session_key, '')), 64);
  v_recent integer;
begin
  if v_message = '' then
    return false;
  end if;
  if v_session !~ '^[A-Za-z0-9_-]{8,64}$' then
    v_session := null;
  end if;

  -- Global cap: at most 600 rows per hour, whatever the source.
  select count(*) into v_recent
  from public.client_error_log
  where occurred_at > v_now - interval '1 hour';
  if v_recent >= 600 then
    return false;
  end if;

  -- Per browser session: at most 10 rows per hour.
  if v_session is not null then
    select count(*) into v_recent
    from public.client_error_log
    where session_key = v_session
      and occurred_at > v_now - interval '1 hour';
    if v_recent >= 10 then
      return false;
    end if;
  end if;

  insert into public.client_error_log (
    occurred_at, kind, message, stack, path, build, user_agent, session_key, signed_in
  ) values (
    v_now,
    left(coalesce(nullif(trim(p_kind), ''), 'error'), 40),
    v_message,
    nullif(left(coalesce(p_stack, ''), 4000), ''),
    nullif(left(coalesce(p_path, ''), 300), ''),
    nullif(left(coalesce(p_build, ''), 60), ''),
    nullif(left(coalesce(p_user_agent, ''), 300), ''),
    v_session,
    auth.uid() is not null
  );

  -- Retention: keep 30 days (about 1 insert in 100 sweeps)
  if random() < 0.01 then
    delete from public.client_error_log
    where occurred_at < v_now - interval '30 days';
  end if;

  return true;
end;
$$;

revoke all on function public.log_client_error(text, text, text, text, text, text, text) from public;
grant execute on function public.log_client_error(text, text, text, text, text, text, text)
  to anon, authenticated, service_role;

-- Staff view: errors grouped by message, most recent first.
create or replace function public.get_client_errors(
  p_hours integer default 72,
  p_limit integer default 100
)
returns table (
  message text,
  kind text,
  occurrences bigint,
  sessions bigint,
  first_seen timestamptz,
  last_seen timestamptz,
  sample_path text,
  sample_stack text,
  sample_user_agent text,
  sample_build text
)
language plpgsql
stable
security definer
set search_path = public
as $$
begin
  if not public.is_staff() then
    raise exception 'STAFF_ONLY' using errcode = '42501';
  end if;

  return query
  with scoped as (
    select e.*
    from public.client_error_log e
    where e.occurred_at > now() - make_interval(hours => least(greatest(coalesce(p_hours, 72), 1), 720))
  ),
  ranked as (
    select
      s.*,
      row_number() over (partition by s.message, s.kind order by s.occurred_at desc) as rn
    from scoped s
  )
  select
    r.message,
    r.kind,
    count(*)::bigint,
    count(distinct coalesce(r.session_key, r.id::text))::bigint,
    min(r.occurred_at),
    max(r.occurred_at),
    max(r.path) filter (where r.rn = 1),
    max(r.stack) filter (where r.rn = 1),
    max(r.user_agent) filter (where r.rn = 1),
    max(r.build) filter (where r.rn = 1)
  from ranked r
  group by r.message, r.kind
  order by max(r.occurred_at) desc
  limit least(greatest(coalesce(p_limit, 100), 1), 500);
end;
$$;

revoke all on function public.get_client_errors(integer, integer) from public, anon;
grant execute on function public.get_client_errors(integer, integer) to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- 3. Draft ideas are private
-- ---------------------------------------------------------------------------
-- "Public can read ideas" used USING (true), so anyone with the anon key could
-- read every member's unpublished drafts through the API (the site only hid
-- them in the UI). Drafts are now readable by their author and staff only.
do $do$
begin
  if to_regclass('public.ideas') is null then
    return;
  end if;
  if not exists (
    select 1 from information_schema.columns
    where table_schema = 'public' and table_name = 'ideas' and column_name = 'status'
  ) then
    raise notice 'ideas.status not found: leaving the read policy unchanged';
    return;
  end if;
  execute 'drop policy if exists "Public can read ideas" on public.ideas';
  execute $pol$
    create policy "Public can read ideas"
      on public.ideas for select
      using (
        lower(coalesce(status, '')) <> 'draft'
        or auth.uid() = user_id
        or public.is_staff()
      )
  $pol$;
end;
$do$;

